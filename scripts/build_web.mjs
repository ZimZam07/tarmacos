// build_web.mjs - production build of the dashboard for static hosting (Vercel).
// Copies web/ to dist/ unchanged, except config.js, which points at the hosted bridge.
//   TARMAC_API_BASE=https://<bridge-host> node scripts/build_web.mjs
// There is no bundling: the dashboard is plain ES modules and runs as written.
import { cpSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const out = join(root, "dist");
const apiBase = (process.env.TARMAC_API_BASE || "").trim().replace(/\/+$/, "");

if (!/^https:\/\/[a-z0-9.-]+(:\d+)?$/i.test(apiBase)) {
  console.error("build_web: TARMAC_API_BASE must be the bridge's https origin, e.g. https://tarmacos-bridge.onrender.com");
  console.error(`build_web: got ${JSON.stringify(apiBase)}`);
  process.exit(1);
}

rmSync(out, { recursive: true, force: true });
cpSync(join(root, "web"), out, { recursive: true });
writeFileSync(join(out, "config.js"),
  `// Generated by scripts/build_web.mjs - do not edit.\nwindow.TARMAC_CONFIG = { apiBase: ${JSON.stringify(apiBase)} };\n`);
console.log(`build_web: dist/ ready, bridge at ${apiBase}`);
